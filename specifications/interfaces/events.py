"""
Interface definitions for Event Bus & Real-Time Session Streaming.
Defines the pub/sub contract for dispatching session events to WebSockets and Slack.
"""

import asyncio
import time
from abc import ABC, abstractmethod
from collections.abc import AsyncIterator, Callable
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class EventType(str, Enum):
    TOKEN = "token"  # Streaming text token
    REASONING_TOKEN = "reasoning_token"  # Streaming thought/reasoning token
    STATUS_CHANGED = "status_changed"  # Agent state or progress message
    TOOL_STARTED = "tool_started"  # Tool execution initiated
    TOOL_COMPLETED = "tool_completed"  # Tool execution completed with output
    FILE_DIFF = "file_diff"  # File modified with diff content
    DECISION_REQUIRED = "decision_required"  # Interactive decision card prompt
    DECISION_SUBMITTED = "decision_submitted"  # User response to decision card
    APPROVAL_REQUIRED = "approval_required"  # Human approval gate (plan execution, risky action)
    LOG_CHUNK = "log_chunk"  # Raw ANSI execution log chunk
    SANDBOX_STATE = "sandbox_state"  # Running, hibernated, starting
    SESSION_UPDATED = "session_updated"  # Session metadata (title, etc.) updated
    USER_MESSAGE = "user_message"  # Accepted user instruction, broadcast to every participant
    PLAN_UPDATED = "plan_updated"  # Agent plan/checklist updated with tasks
    FOLLOWUP_SUGGESTION = "followup_suggestion"  # Probable next question generated by LLM
    SUBAGENT_STARTED = "subagent_started"  # Specialized subagent spawned
    SUBAGENT_PROGRESS = "subagent_progress"  # Nested subagent reasoning or tool event
    SUBAGENT_COMPLETED = "subagent_completed"  # Subagent turn finished with findings
    PROCESS_STARTED = "process_started"  # A background process started in the sandbox
    PROCESS_EXITED = "process_exited"  # A background process ended (exited, stopped or lost)
    POST_FAILURE_SYNTHESIS = (
        "post_failure_synthesis"  # Final synthesis triggered after turn budget exhaustion or error
    )
    GITHUB_EVENT = "github_event"  # Something happened on a pull request the session follows
    CONTEXT_COMPACTED = "context_compacted"  # Session context window compacted
    GOAL_UPDATED = "goal_updated"  # Goal progress or budget update
    CONTINUATION_SCHEDULED = "continuation_scheduled"  # Automatic turn continuation scheduled
    WAIT_STARTED = "wait_started"  # Turn entered durable waiting state
    WAIT_COMPLETED = "wait_completed"  # Wake trigger resumed waiting session
    ARTIFACT_CREATED = "artifact_created"  # Durable session deliverable created
    ARTIFACT_UPDATED = "artifact_updated"  # Durable session deliverable updated
    TASK_STARTED = "task_started"  # Background detached task started
    TASK_COMPLETED = "task_completed"  # Background detached task completed
    ERROR = "error"  # Unrecoverable or tool error


@dataclass
class SessionEvent:
    session_id: str
    event_type: EventType
    payload: dict[str, Any]
    timestamp_ms: int = field(default_factory=lambda: int(time.time() * 1000))
    # Monotonic per-session sequence, assigned by the bus on publish. Clients store the
    # last one they applied and send it back as `resume` after a reconnect, so a dropped
    # socket can be replayed without losing tokens or duplicating them.
    seq: int = 0


class EventBusProtocol(ABC):
    """
    Contract for broadcasting session events across API WebSockets,
    background workers, and the Slack Assistant bot.
    """

    @abstractmethod
    async def publish(self, event: SessionEvent) -> None:
        """Publishes an event to the session topic."""
        pass

    @abstractmethod
    def subscribe(
        self,
        session_id: str,
        client_id: str | None = None,
    ) -> AsyncIterator[SessionEvent]:
        """
        Subscribes to all real-time events for a specific session.
        Used by the WebSocket endpoint to stream events to Next.js.
        """
        pass

    @abstractmethod
    async def attach(self, session_id: str) -> None:
        """
        Prepares this process to serve ``session_id``. A bus shared between replicas adopts
        the cluster-wide sequence here; a single-process bus has nothing to do.
        """
        pass

    @abstractmethod
    def latest_seq(self, session_id: str) -> int:
        """
        Returns the sequence number of the most recently published event for a session
        (0 when nothing has been published yet).
        """
        pass

    @abstractmethod
    def replay_since(self, session_id: str, last_seq: int) -> tuple[list[SessionEvent], bool]:
        """
        Returns the retained events published after ``last_seq`` together with whether the
        replay is continuous.

        ``continuous=False`` means the requested point has already been evicted from the
        bounded history, so the caller must fall back to a full session snapshot instead
        of trusting an incomplete stream.
        """
        pass

    def open_queue(self, session_id: str) -> tuple[asyncio.Queue[SessionEvent], Callable[[], None]]:
        """Register a subscriber queue *synchronously* and return ``(queue, close)``.

        ``subscribe`` registers lazily on the first ``__anext__``, which leaves a window in
        which an event published right after the call is missed. Transports that start a
        turn and then watch it (Slack) need the registration to be in place first.
        """
        raise NotImplementedError
